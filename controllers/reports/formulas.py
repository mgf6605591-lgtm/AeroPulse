# controllers/reports/formulas.py
"""Откуда взялась ячейка свода: правила, по которым выгрузка пишет формулу.

В книгу уходили только числа, и сложение, которым свод их получил, в файле не
оставалось: «Итого» ничем не отличался от набранной руками цифры, а поправить в
Excel одну колонку и увидеть новый итог было нельзя.

Правило описывает сумму — «эта ячейка есть сумма вот тех» — и ничего больше:
ни процентов, ни разностей в сводах нет. Двух видов хватает на все формы: итог
по строке (колонка складывает соседние колонки) и итог по колонке (строка
складывает другие строки).

Сходится ли сумма, здесь не проверяется. Это делает выгрузка
([controllers/export_controller.py](controllers/export_controller.py)): правило
говорит, что ячейка задумана суммой, а совпадает ли она с ней на самом деле,
видно только по значениям — до них решать рано. Разница существенна для строк и
граф бланка 15-ГА и для тоннокилометража 12-ГА: их приложение не считает, а
хранит присланными, и сойтись они обязаны не всегда.
"""
from collections.abc import Mapping
from dataclasses import dataclass, field

# Ячейка листа как её видит выгрузка: номер строки данных и номер колонки, оба
# от нуля. Ни о шапке отчёта, ни о рядах заголовка правило не знает — поправку
# на них делает тот, кто пишет книгу.
CellRef = tuple[int, int]

# Ячейка → способы её сложить, каждый списком слагаемых. Столько выгрузке и
# нужно знать о своде.
FormulaMap = dict[CellRef, tuple[tuple[CellRef, ...], ...]]


@dataclass(frozen=True)
class PivotFormulas:
    """Какие ячейки свода — суммы других.

    `column_sums` — ключ колонки → ключи слагаемых в той же строке. Правило одно
    на всю колонку: итог в своде собран по одному закону в каждой строке.
    `row_sums` — номер строки → номера строк-слагаемых в той же колонке; здесь
    правило, наоборот, о единственной строке, и колонки ему безразличны.
    """

    column_sums: Mapping[str, tuple[str, ...]] = field(default_factory=dict)
    row_sums: Mapping[int, tuple[int, ...]] = field(default_factory=dict)

    def __bool__(self) -> bool:
        return bool(self.column_sums or self.row_sums)

    def operands(
        self,
        row: int,
        col: int,
        key: str,
        col_by_key: Mapping[str, int],
    ) -> tuple[tuple[CellRef, ...], ...]:
        """Способы сложить ячейку, в порядке предпочтения; пусто — ни одного.

        Способов бывает два, и на пересечении итоговой строки с итоговой
        колонкой годятся оба. Первым идёт правило колонки: слагаемых у него
        меньше, и они посчитаны тем же сводом в той же строке.

        Отдаются оба, а не только первый, потому что сложение бланка сходится не
        всегда: там, где графа «Всего» разошлась с присланными отправлено и
        принято, итог по строке остаётся верным — и как раз в этом случае
        формула в нём нужнее всего. Какой из способов сошёлся, решает выгрузка.
        """
        ways: list[tuple[CellRef, ...]] = []

        columns = self.column_sums.get(key)
        if columns:
            cells: list[CellRef] = []
            for operand_key in columns:
                operand_col = col_by_key.get(operand_key)
                if operand_col is None:
                    # Слагаемое не показано — этим способом не сложить.
                    cells = []
                    break
                cells.append((row, operand_col))
            if cells:
                ways.append(tuple(cells))

        rows = self.row_sums.get(row)
        if rows:
            ways.append(tuple((operand_row, col) for operand_row in rows))

        return tuple(ways)


# Свод без единой формулы: подробная таблица и своды, где складывать нечего.
NO_FORMULAS = PivotFormulas()

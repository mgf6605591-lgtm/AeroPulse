# utils/entity_names.py
"""Сравнение названия предприятия из отчёта с записью справочника.

Отчёт называет предприятие так, как оно записано в уставе: «Акционерное общество
"Авиакомпания "АЛРОСА"». В справочнике то же предприятие заведено коротко — «АО
Авиакомпания АЛРОСА». Посимвольное сравнение их не сводит, и импорт «предприятие
из файла» заводил бы вторую запись рядом с существующей, разложив отчётность
одной авиакомпании по двум строкам свода.

Приводится только то, в чём записи расходятся заведомо: регистр, кавычки любого
начертания, ё/е, лишние пробелы и знаки, организационно-правовая форма словами
вместо аббревиатуры. Слова самого названия не отбрасываются: «Авиакомпания» стоит
почти в каждом, и выбросив его, «АО Авиакомпания Якутия» и «АО Якутия» слились бы
в одно предприятие — а это разные юридические лица, если сдают разные отчёты.
"""
import re
from typing import Optional

# Организационно-правовая форма: как её пишут словами → как в справочнике.
# Порядок применения — от длинных к коротким, иначе «закрытое акционерное
# общество» превратилось бы в «закрытое ао».
LEGAL_FORMS = {
    "федеральное государственное унитарное предприятие": "фгуп",
    "государственное унитарное предприятие": "гуп",
    "муниципальное унитарное предприятие": "муп",
    "федеральное казенное предприятие": "фкп",
    "государственное казенное предприятие": "гкп",
    "публичное акционерное общество": "пао",
    "открытое акционерное общество": "оао",
    "закрытое акционерное общество": "зао",
    "акционерное общество": "ао",
    "общество с ограниченной ответственностью": "ооо",
}

_LEGAL_FORM_PATTERNS = tuple(
    (re.compile(rf"\b{re.escape(phrase)}\b"), short)
    for phrase, short in sorted(LEGAL_FORMS.items(), key=lambda item: -len(item[0]))
)

# Всё, что не буква и не цифра, — разделитель: кавычки, точки, запятые, дефисы,
# подчёркивания (ими в бланках дописывают название в подпись).
_NOT_A_LETTER = re.compile(r"[\W_]+", re.UNICODE)


def normalized_entity_name(name: Optional[str]) -> str:
    """Название в виде, пригодном для сравнения. Пустое — если сравнивать нечего."""
    text = str(name or "").lower().replace("ё", "е")
    text = _NOT_A_LETTER.sub(" ", text).strip()
    for pattern, short in _LEGAL_FORM_PATTERNS:
        text = pattern.sub(short, text)
    return " ".join(text.split())


def same_entity_name(left: Optional[str], right: Optional[str]) -> bool:
    """Одно ли это предприятие. Два пустых названия одним предприятием не считаются."""
    normalized = normalized_entity_name(left)
    return bool(normalized) and normalized == normalized_entity_name(right)

# services/import_outcome.py
"""Итог загрузки файла — тип, а не словарь со строковыми ключами (ARCH-18).

Результат проходит четыре слоя: `DataImporter` собирает счётчики, `ImportService`
дописывает имя файла и период, `ImportRunner` добавляет свой отказ при
исключении, окно читает всё это и складывает отчёт по пакету. Ходил он обычным
`dict`, и ключи набирались по дороге.

Читалось всё через `result.get(...)` с умолчанием, поэтому **опечатка в ключе
давала не ошибку, а тихое «ничего»**: пропавший `success` превращал удачную
загрузку в неудачную, пропавший `period_required` — вопрос о периоде в отказ.
Ни линтер, ни тесты такого не видят, если тест написан теми же ключами.

Приём тот же, каким в блоке 35 был заменён словарь фильтров (`ReportFilters`):
замороженный тип с явными полями. Опечатка в имени поля — `AttributeError` на
месте, а не пустое значение через три слоя.

Почему модуль здесь. Тип нужен и `importers/`, и `forms/`; `importers` уже
импортирует `services.journal_service`, а `forms` — `services.import_service`.
В `importers/` он завёл бы ребро `forms → importers`, которого нет.
"""
from dataclasses import dataclass, replace

__all__ = ["ImportOutcome", "PeriodRequired", "failure", "replace"]


@dataclass(frozen=True)
class ImportOutcome:
    """Что стало с одним файлом.

    Счётчики отдельными полями, а не одним «сколько всего»: добавленное,
    обновлённое и удалённое пользователь читает по-разному — последнее означает,
    что отчёт заменил период целиком (DATA-5).
    """

    success: bool
    message: str = ""

    # Дописывает `ImportService`: разбор знает содержимое файла, но не его имя.
    source_file: str | None = None
    sheet_name: str | None = None

    # Отчётный период файла. Месяц — имя члена `Months`, как его отдаёт разбор.
    month: str | None = None
    year: int | None = None

    imported: int = 0
    updated: int = 0
    removed: int = 0
    # Записи, заведённые в справочнике по ходу импорта: они перечисляются
    # пользователю поимённо, молча пополнять справочник нельзя.
    created_entities: tuple[str, ...] = ()


@dataclass(frozen=True)
class PeriodRequired(ImportOutcome):
    """Файл не загружен: отчётный период не прочитался, и его должны спросить.

    Отдельный тип, а не поле `period_required`, потому что это не свойство
    исхода, а требование к вызывающему: «спроси период и позови снова».
    Проверяется через `isinstance`, и забыть про эту ветку сложнее, чем
    не заметить булев ключ среди девяти других.

    Наследник `ImportOutcome`, а не отдельный класс: тот, кто спрашивать не
    станет — а `ImportRunner` не спрашивает дважды об одном файле, — обязан
    показать его как обычный отказ, и для этого у исхода уже всё есть.

    `month` и `year` — то, что разобрать всё-таки удалось: ими заполняется
    диалог, чтобы человек не вводил заново уже прочитанное.
    """

    success: bool = False


def failure(message: str, **fields) -> ImportOutcome:
    """Отказ с причиной. Счётчики при отказе нулевые, и повторять это незачем."""
    return ImportOutcome(success=False, message=message, **fields)

# forms/models/roles.py
"""Роли данных для выгрузки: чем ячейка является помимо своего вида на экране.

`DisplayRole` отдаёт строку, подготовленную для экрана: разряды разделены
пробелом, дробная часть — запятой. Экспорт брал именно её, и в XLSX все числовые
ячейки оказывались текстом (FUNC-2): Excel помечал их «Число сохранено как
текст», а суммировать и строить диаграммы по такому файлу было нельзя.

Экран и файл нуждаются в разном, поэтому рядом с `DisplayRole` у моделей есть
роль сырого значения: первая говорит, как показать, вторая — что показывается.

Третья роль — о происхождении ячейки. Итоги свод считает сам, но в книгу
уходило только их значение, и в файле «Итого» ничем не отличался от набранной
руками цифры. Роль отдаёт слагаемые, из которых ячейка сложена, — по ним
выгрузка пишет формулу. Модель их не выдумывает: правила приносит построитель
свода ([controllers/reports/formulas.py](controllers/reports/formulas.py)).
"""
from PyQt6.QtCore import Qt

RAW_VALUE_ROLE = int(Qt.ItemDataRole.UserRole) + 1

# Способы сложить ячейку: кортеж наборов, каждый — пары «строка, колонка»
# модели; `None`, если ячейка ничего не складывает. Номера — модели, а не листа:
# о шапке книги и рядах заголовка знает только сборщик книги.
FORMULA_ROLE = int(Qt.ItemDataRole.UserRole) + 2

# forms/models/formatting.py
"""Как число выглядит в таблице.

Сводная таблица разделяла разряды пробелом, а дробную часть запятой; подробная
отдавала `str(value)` как есть (BUG-26). Одно и то же число выводилось в двух
режимах одного отчёта по-разному — а сверяют его с бланком глазами именно в
подробном, потому что оттуда удаляют записи.

Правило показа живёт в слое представления, а не в `utils/`, намеренно: выгрузка
в XLSX берёт `RAW_VALUE_ROLE` и форматирования не касается вовсе. Общий помощник
«где-нибудь в утилитах» — приглашение позвать его из экспорта, а это ровно тот
путь, которым числа однажды уже уехали в файл текстом (FUNC-2).
"""
from decimal import Decimal

# Русская запись: пробел разделяет разряды, запятая отделяет дробную часть.
_THOUSANDS_SEPARATOR = " "
_DECIMAL_SEPARATOR = ","


def format_number_ru(value: int | float | Decimal) -> str:
    """Число в русской записи: «1 234 567», «1 234,57».

    Целое показывается без дробной части: приписывать «,00» количеству рейсов
    незачем. `Decimal` форматируется напрямую, без промежуточного `float` —
    точность значения и держится на том, что этого приведения нет (BUG-4).
    """
    if value == int(value):
        return f"{int(value):,}".replace(",", _THOUSANDS_SEPARATOR)
    return (
        f"{value:,.2f}"
        .replace(",", _THOUSANDS_SEPARATOR)
        .replace(".", _DECIMAL_SEPARATOR)
    )
